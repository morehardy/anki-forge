"""Verify the archive and recompute statistics; does not rerun exports or Anki."""
from pathlib import Path,PurePosixPath
import hashlib,json,subprocess,sys,tarfile,tempfile
D=Path(__file__).resolve().parent
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
manifest=json.loads((D/'archive-manifest.json').read_text())['files']
with tempfile.TemporaryDirectory(prefix='anki-rss-replay-') as tmp:
 root=Path(tmp)
 with tarfile.open(D/'evidence.tar.gz','r:gz') as tar:
  seen=set()
  for member in tar.getmembers():
   path=PurePosixPath(member.name)
   assert member.isfile() and path.parts[0]=='evidence' and '..' not in path.parts and not path.is_absolute()
   rel=str(PurePosixPath(*path.parts[1:]));assert rel in manifest and rel not in seen;seen.add(rel)
   data=tar.extractfile(member).read();assert len(data)==manifest[rel]['bytes'] and hashlib.sha256(data).hexdigest()==manifest[rel]['sha256']
   dest=root/path;dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(data)
  assert seen==set(manifest)
 w=root/'evidence'
 for name,folder in [('baseline-155322-source.json','baseline-source'),('candidate-155409-source.json','source')]:
  for path,digest in json.loads((w/name).read_text()).items():assert sha(w/folder/path)==digest,(folder,path)
 for group in (w/'records').iterdir():
  for row in json.loads((group/'results.json').read_text())['rows']:(w/row['directory']/'tmp').mkdir(exist_ok=True)
 for script in ['analyze.py','contrasts.py','audit.py']:
  args=[sys.executable,str(w/'scripts'/script)]+(['--offline'] if script=='audit.py' else [])
  result=subprocess.run(args,text=True,capture_output=True);assert result.returncode==0,result.stderr
 for name in ['analysis.json','contrasts.json']:assert (w/name).read_bytes()==(D/name).read_bytes(),name
 audit=json.loads((w/'audit.json').read_text());assert audit['exports']==1826 and audit['anki']==185
 result={'status':'passed','archived_files_verified':len(seen),'source_files_verified':len(json.loads((w/'baseline-155322-source.json').read_text()))+len(json.loads((w/'candidate-155409-source.json').read_text())),'statistics':'analysis.json and contrasts.json independently regenerated byte-identical','exports_reconciled':audit['exports'],'anki_records_reconciled':audit['anki'],'scope':'Retained records only: no exporter execution, fresh APKG validation, fresh Anki import, or omitted binary/media verification.'}
(D/'replay-result.json').write_text(json.dumps(result,indent=2)+'\n');print(json.dumps(result,indent=2))
